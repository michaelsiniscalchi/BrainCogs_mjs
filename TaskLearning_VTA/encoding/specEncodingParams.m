function params = specEncodingParams(params, modelName)

if nargin<2 %params.modelName can contain multiple model names; use ARG #2 to specify one
    modelName = params.modelName; %Only useful if scalar
end

%Predictors for full/partial models
%Initialize
params.positionSpline = false;
params.initFcn_position = @nan; %ITI position

%Default B-spline parameters
%Position
bSpline.position.degree      = 3; %degree for position splines
bSpline.position.binWidth    = 1; %bin width in cm
bSpline.position.df          = 7; %number of terms for position splines

%Cues
bSpline.cue.degree      = 3; %degree of each (Bernstein polynomial) term
bSpline.cue.nSamples    = 90; %N time points for spline basis set;
bSpline.cue.df          = 9; %number of terms:= order + N internal knots

%Reward
bSpline.outcome.degree      = 3; %degree of each (Bernstein polynomial) term
bSpline.outcome.nSamples    = 150; %N time points for spline basis set; 
bSpline.outcome.df          = 15; %number of terms:= order + N internal knots
params.bSpline = bSpline;

switch modelName

    case 'RPE'
        params.predictorNames = ["start",...
            "firstLeftPuff","firstRightPuff","firstLeftTower","firstRightTower",...
            "position",...
            "reward","noReward",...
            "heading","speed","acceleration",...
            "noPuffs_position", "noTowers_position",... %Interaction terms
            "priorOutcome_position", "priorOutcome_start",... %Interaction terms
            ];
        params.positionSpline = true;

    case 'allCues'
        params.predictorNames = ["start",...
            "leftPuffs","rightPuffs","leftTowers","rightTowers"...
            "position",...
            "reward","noReward",...
            "heading","speed","acceleration"];
        params.positionSpline = true;

    case 'FM'
        params.predictorNames = ["start",...
            "firstLeftPuff","firstRightPuff","firstLeftTower","firstRightTower",...
            "towerSide_position", "puffSide_position", "position",...
            "reward","noReward",...
            "heading","speed"];
        params.positionSpline = true;
   
    case 'posXcueSide'
        params.predictorNames = ["start",...
            "towerSide_position", "puffSide_position",...
            "position",...
            "reward","noReward",...
            "heading","speed","acceleration"];
        params.positionSpline = true;


    case 'firstCues'
        params.predictorNames = ["start",...
           "firstLeftPuff","firstRightPuff","firstLeftTower","firstRightTower",...
            "position",...
            "reward","noReward",...
            "heading","speed"];
        params.positionSpline = true;

   
    case 'cues_pos_rew'
        params.predictorNames = [...
            "leftPuffs","rightPuffs","leftTowers","rightTowers"...
            "position",...
            "reward","noReward"...
            ];
        params.positionSpline = true;


    %Minimal Models
    case 'only_position'
        params.predictorNames = "position";
        params.positionSpline = true; 

    case 'position_speed'
        params.predictorNames = ["position","speed"];
        params.positionSpline = true;

    case 'only_cues'
        params.predictorNames = [...
            "firstLeftPuff","firstRightPuff","firstLeftTower","firstRightTower",...
            "leftPuffs","rightPuffs","leftTowers","rightTowers",...
            ];
         
    case 'only_allCues'
        params.predictorNames = [...
            "leftPuffs","rightPuffs","leftTowers","rightTowers"...
            ];
    
    case 'only_firstCues'
        params.predictorNames = [
            "firstLeftPuff","firstRightPuff","firstLeftTower","firstRightTower"...
            ];

    case 'posXcueSide_pos' %Minimal posXcueSide model with position term
        params.predictorNames = [...
            "towerSide_position","puffSide_position","position",...
            ];
        params.positionSpline = true;

end

%List variables by type
pNames = params.predictorNames;
varNames.eventVars = ["start",...
            "firstLeftPuff","firstRightPuff","firstLeftTower","firstRightTower",...
            "leftPuffs","rightPuffs","leftTowers","rightTowers",...
            "reward","noReward",...
            "priorOutcome_start",... %Interaction terms
            ];
varNames.positionVars = [...
    "position",...
    "towerSide_position","puffSide_position"... %Transformed into separate kernels later after summing with main position kernel
    "leftPuffs_position","rightPuffs_position",...
    "leftTowers_position","rightTowers_position",...
    "noPuffs_position", "noTowers_position",...
    "priorOutcome_position",... %Transformed into separate rewarded & unrewarded kernels later after summing with main position kernel
    "priorRewarded_position","priorUnrewarded_position",...
    ];
varNames.indicatorVars = ["ITI","trialIdx","accuracy","priorOutcome"];
varNames.kinematicVars = ["heading","speed","velocity","acceleration"];

for f = string(fieldnames(varNames))'
    params.(f) = []; %Initialize
    if any(ismember(pNames, varNames.(f)))
        params.(f) = pNames(ismember(pNames,varNames.(f)));
    end
end

%Subtypes (for referencing bSpline params)
params.cueVarNames = ["start",...
            "firstLeftPuff","firstRightPuff","firstLeftTower","firstRightTower",...
            "leftPuffs","rightPuffs","leftTowers","rightTowers",...
             "priorOutcome_start",... %Interaction term
             ]; 
params.outcomeVarNames = ["reward","noReward"];
params.positionVarNames = ["position",...
        "towerSide_position","puffSide_position"... %Interaction terms
        "leftPuffs_position","rightPuffs_position",... %Some models may have cueType x pos interactions as 4 separate terms
        "leftTowers_position","rightTowers_position",...
        "noPuffs_position", "noTowers_position",...
        "priorOutcome_position",...
        ];